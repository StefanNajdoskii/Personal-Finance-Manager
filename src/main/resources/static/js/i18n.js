const LANG_KEY = "fintrack-lang";
let currentLang = localStorage.getItem(LANG_KEY)
    || (navigator.language?.toLowerCase().startsWith("mk") ? "mk" : "en");

export function getLang() {
    return currentLang;
}

export function t(key, vars = {}) {
    const text = DICTIONARY[currentLang]?.[key] ?? DICTIONARY.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}

export function applyI18n(root = document) {
    document.documentElement.lang = currentLang;
    root.querySelectorAll("[data-i18n]").forEach(el => {
        el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    root.querySelectorAll("[data-i18n-label]").forEach(el => {
        el.setAttribute("aria-label", t(el.dataset.i18nLabel));
    });
}

export function setLang(lang) {
    currentLang = DICTIONARY[lang] ? lang : "en";
    localStorage.setItem(LANG_KEY, currentLang);
    applyI18n();
}
